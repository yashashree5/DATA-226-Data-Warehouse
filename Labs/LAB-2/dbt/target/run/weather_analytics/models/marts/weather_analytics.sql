
  
    

        create or replace transient table USER_DB_PUMA.ANALYTICS.weather_analytics
         as
        (-- Monthly weather summary
SELECT
    YEAR,
    MONTH,
    DATE_TRUNC('MONTH', FORECAST_DATE) AS MONTH_DATE,
    
    -- Temperature stats
    COUNT(*) AS TOTAL_DAYS,
    ROUND(AVG(AVG_TEMP), 2) AS AVG_TEMP,
    ROUND(MAX(MAX_TEMP), 2) AS MAX_TEMP,
    ROUND(MIN(MIN_TEMP), 2) AS MIN_TEMP,
    
    -- Precipitation stats
    ROUND(SUM(PRECIPITATION), 2) AS TOTAL_PRECIPITATION,
    ROUND(AVG(PRECIPITATION), 2) AS AVG_PRECIPITATION,
    SUM(CASE WHEN PRECIPITATION > 0 THEN 1 ELSE 0 END) AS RAINY_DAYS,
    
    -- Wind stats
    ROUND(AVG(WIND_SPEED), 2) AS AVG_WIND_SPEED,
    ROUND(MAX(WIND_SPEED), 2) AS MAX_WIND_SPEED

FROM USER_DB_PUMA.ANALYTICS.stg_weather
GROUP BY YEAR, MONTH, DATE_TRUNC('MONTH', FORECAST_DATE)
ORDER BY YEAR, MONTH
        );
      
  